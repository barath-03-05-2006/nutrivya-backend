package com.nutritrack.entity;

import jakarta.persistence.*;
import java.time.Instant;

/**
 * A long-lived opaque token exchanged for a fresh short-lived JWT access token.
 * One row per active session — creating a new refresh token for a user
 * replaces any previous one (see RefreshTokenService), so logging in on a
 * new device effectively logs the old one out. Good enough for this app's
 * single-device-per-client usage pattern.
 */
@Entity
@Table(name = "refresh_tokens")
public class RefreshToken {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, unique = true, length = 64)
    private String token;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @Column(nullable = false)
    private Instant expiryDate;

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }
    public String getToken() { return token; }
    public void setToken(String token) { this.token = token; }
    public User getUser() { return user; }
    public void setUser(User user) { this.user = user; }
    public Instant getExpiryDate() { return expiryDate; }
    public void setExpiryDate(Instant expiryDate) { this.expiryDate = expiryDate; }
}
